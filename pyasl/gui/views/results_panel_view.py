    def _on_download_zip_clicked(self):
        """Export all visualizations and create a ZIP archive."""
        selected = self._list_widget.selectedItems()
        if not selected:
            return
        result_id = selected[0].data(Qt.ItemDataRole.UserRole)
        self._controller.download_all_zip(result_id)

    def _on_dashboard_clicked(self):
        """Open dedicated Result Analytics Dashboard for the selected result."""
        selected = self._list_widget.selectedItems()
        if not selected:
            return
        result_id = selected[0].data(Qt.ItemDataRole.UserRole)
        res_item = self._controller.state.get_result(result_id)
        if not res_item:
            return

        from pyasl.gui.services.result_service import ResultService
        from pyasl.gui.views.result_window.result_window import ResultWindow

        results_dir = os.path.join(os.path.expanduser("~"), ".pyasl_results")
        os.makedirs(results_dir, exist_ok=True)
        service = ResultService(results_dir)

        res_type = getattr(res_item, "type", getattr(res_item, "result_type", "pipeline"))
        if res_type == "pipeline":
            processed = service.process_pipeline_result(res_item.summary, {"summary": res_item.full_output})
        else:
            processed = service.process_batch_result([{"status": res_item.status, "summary": res_item.summary}], res_item.data_dirs)

        processed.name = res_item.name

        # Create dashboard dialog window
        from PyQt6.QtWidgets import QDialog, QVBoxLayout
        dialog = QDialog(self)
        dialog.setWindowTitle(f"Result Analytics Dashboard — {res_item.name}")
        dialog.resize(1100, 750)
        layout = QVBoxLayout(dialog)
        layout.setContentsMargins(0, 0, 0, 0)

        win = ResultWindow(service, parent=dialog)
        win.set_result(processed)
        layout.addWidget(win)

        dialog.exec()
