    def _on_selection_changed(self):
        selected = self._list_widget.selectedItems()
        if not selected:
            self._right_stack.setCurrentIndex(0)
            return

        result_id = selected[0].data(Qt.ItemDataRole.UserRole)
        result = self._controller.state.get_result(result_id)
        if result:
            self._right_stack.setCurrentIndex(1)
            self._detail_title.setText(result.name)
            
            color = Colors.DARK_PURPLE if result.status == "COMPLETED" else Colors.BRIGHT_CORAL
            self._detail_subtitle.setText(f"{result.timestamp} | <span style='color:{color}; font-weight:bold;'>{result.status}</span>")
            
            self._output_browser.setPlainText(result.full_output)

            # Show/populate visualization gallery
            self._clear_viz_gallery()
            if result.visualizations:
                self._viz_section.show()
                for viz in result.visualizations:
                    data = {
                        "path": viz.file_path,
                        "metadata": viz.metadata,
                        "png_bytes": viz.png_bytes,
                        "error": viz.error,
                    }
                    card = NpyCard(data)
                    idx = self._viz_container_layout.count() - 1
                    self._viz_container_layout.insertWidget(idx, card)

                valid_count = sum(1 for v in result.visualizations if v.is_valid)
                total_count = len(result.visualizations)
                self._viz_title.setText(
                    f"📊  Output Visualizations ({valid_count}/{total_count} files)"
                )
                self._export_viz_btn.setEnabled(valid_count > 0)
                self._download_zip_btn.setEnabled(valid_count > 0)
            else:
                self._viz_section.hide()
                self._export_viz_btn.setEnabled(False)
                self._download_zip_btn.setEnabled(False)

    def _clear_viz_gallery(self):
        """Remove all NpyCard widgets from the gallery."""
        while self._viz_container_layout.count() > 1:
            item = self._viz_container_layout.takeAt(0)
            widget = item.widget()
            if widget:
                widget.deleteLater()
        self._viz_title.setText("📊  Output Visualizations")
        self._export_viz_btn.setEnabled(False)
        self._download_zip_btn.setEnabled(False)
        self._scan_progress.hide()
        self._scan_label.hide()

    def _on_copy_clicked(self):
        clipboard = QApplication.clipboard()
        clipboard.setText(self._output_browser.toPlainText())
        
        # Brief visual feedback on the button
        orig_text = self._copy_btn.text()
        self._copy_btn.setText("✔ Copied!")
        QTimer.singleShot(1500, lambda: self._copy_btn.setText(orig_text))

    def _on_export_clicked(self):
        selected = self._list_widget.selectedItems()
        if not selected:
            return
            
        result_id = selected[0].data(Qt.ItemDataRole.UserRole)
        result = self._controller.state.get_result(result_id)
        if not result:
            return

        file_filter = "Text Files (*.txt);;JSON Files (*.json);;All Files (*)"
        default_name = f"result_{result.type}_{result.timestamp.replace(':', '-')}.txt"
        
        path, _ = QFileDialog.getSaveFileName(
            self, "Export Result", default_name, file_filter
        )
        
        if path:
            try:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(f"Task: {result.name}\n")
                    f.write(f"Status: {result.status}\n")
                    f.write(f"Timestamp: {result.timestamp}\n")
                    f.write("-" * 40 + "\n\n")
                    f.write(result.full_output)
                QMessageBox.information(self, "Export Successful", f"Result exported to:\n{path}")
            except Exception as e:
                QMessageBox.critical(self, "Export Error", f"Failed to export result:\n{e}")

    def _on_delete_clicked(self):
        selected = self._list_widget.selectedItems()
        if not selected:
            return
            
        result_id = selected[0].data(Qt.ItemDataRole.UserRole)
        
        reply = QMessageBox.question(
            self, 'Delete Result', 'Are you sure you want to delete this result?',
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No
        )
        
        if reply == QMessageBox.StandardButton.Yes:
            self._controller.remove_result(result_id)

    def _on_clear_clicked(self):
        reply = QMessageBox.question(
            self, 'Clear All Results', 'Are you sure you want to delete all results?',
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No
        )
        
        if reply == QMessageBox.StandardButton.Yes:
            self._controller.clear_all()

