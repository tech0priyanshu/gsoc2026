    # ------------------------------------------------------------------
    # Controller Signal Handlers
    # ------------------------------------------------------------------

    def _on_result_added(self, item: ResultItem):
        # Format the display text for the list item
        icon_str = "✅" if item.status == "COMPLETED" else "❌"
        display_text = f"{icon_str} {item.name}\n{item.timestamp}"
        
        list_item = QListWidgetItem(display_text)
        list_item.setData(Qt.ItemDataRole.UserRole, item.id)
        
        # Insert at top
        self._list_widget.insertItem(0, list_item)
        self._update_empty_state()

    def _on_result_removed(self, result_id: str):
        for i in range(self._list_widget.count()):
            item = self._list_widget.item(i)
            if item.data(Qt.ItemDataRole.UserRole) == result_id:
                self._list_widget.takeItem(i)
                break
        self._update_empty_state()

    def _on_results_cleared(self):
        self._list_widget.clear()
        self._clear_viz_gallery()
        self._update_empty_state()

    # ------------------------------------------------------------------
    # Visualization Signal Handlers
    # ------------------------------------------------------------------

    def _on_visualization_ready(self, data: dict):
        """Add a new NpyCard to the gallery as it arrives."""
        # Show the viz section if hidden
        if self._viz_section.isHidden():
            self._viz_section.show()

        # Insert card before the stretch spacer
        card = NpyCard(data)
        idx = self._viz_container_layout.count() - 1  # before stretch
        self._viz_container_layout.insertWidget(idx, card)

    def _on_all_visualizations_ready(self, result_id: str):
        """All visualizations done — enable export buttons."""
        self._scan_progress.hide()
        self._scan_label.hide()

        result = self._controller.state.get_result(result_id)
        if result and result.visualizations:
            valid_count = sum(1 for v in result.visualizations if v.is_valid)
            total_count = len(result.visualizations)
            self._viz_title.setText(
                f"📊  Output Visualizations ({valid_count}/{total_count} files)"
            )
            self._export_viz_btn.setEnabled(valid_count > 0)
            self._download_zip_btn.setEnabled(valid_count > 0)
        else:
            self._viz_title.setText("📊  Output Visualizations (0 files)")

    def _on_scan_progress(self, current: int, total: int):
        """Update the scan progress bar."""
        self._scan_progress.show()
        self._scan_label.show()
        self._scan_progress.setMaximum(max(total, 1))
        self._scan_progress.setValue(current)
        self._scan_label.setText(f"Scanning {current}/{total}…")

    def _on_export_finished(self, path: str):
        """Show confirmation when export completes."""
        QMessageBox.information(
            self,
            "Export Complete",
            f"Visualizations saved to:\n{path}",
        )

